import argparse
import glob
import logging
import os

from hydra import compose, initialize_config_dir
from omegaconf import DictConfig

from utils.logging_helper import setup_logging
from utils.memory_cluster_debug import (
    build_observations,
    load_frame,
    load_metadata,
    load_local_map_snapshot,
    build_stub_local_map_manager,
)
from utils.memory_cluster_manager import MemoryClusterManager


def _compose_cfg(config_dir: str, config_name: str) -> DictConfig:
    with initialize_config_dir(config_dir=config_dir, job_name="memory_cluster_debug"):
        cfg = compose(config_name=config_name)
    return cfg


def _resolve_config_paths(script_dir: str, config_path: str) -> str:
    candidate = config_path
    if not os.path.isabs(candidate):
        candidate = os.path.join(script_dir, config_path)
    return os.path.abspath(candidate)


def parse_args():
    parser = argparse.ArgumentParser(
        description="Offline debugger for MemoryCluster representative frame selection."
    )
    parser.add_argument(
        "--replay-dir",
        required=True,
        help="Directory containing recorded frames (generated by memory_cluster_debug recorder).",
    )
    parser.add_argument(
        "--config-path",
        default="../config",
        help="Hydra config directory (same as runner_dataset config_path).",
    )
    parser.add_argument(
        "--config-name",
        default="runner_dataset",
        help="Hydra config name to compose (default: runner_dataset).",
    )
    parser.add_argument(
        "--max-frames",
        type=int,
        default=None,
        help="Optionally limit number of frames to replay.",
    )
    parser.add_argument(
        "--output-path",
        default=None,
        help="Override memory_cluster.keyframe_dir during replay (useful to keep originals).",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    script_dir = os.path.dirname(os.path.abspath(__file__))
    replay_dir = os.path.abspath(os.path.expanduser(args.replay_dir))
    if not os.path.isdir(replay_dir):
        raise FileNotFoundError(f"Replay directory not found: {replay_dir}")

    config_dir = _resolve_config_paths(script_dir, args.config_path)
    cfg = _compose_cfg(config_dir=config_dir, config_name=args.config_name)

    setup_logging(output_path=cfg.output_path, config_path=cfg.logging_config)
    logger = logging.getLogger(__name__)
    logger.info("[MemoryClusterDebug] Replay dir: %s", replay_dir)

    metadata = load_metadata(replay_dir)
    memory_cluster_cfg = getattr(cfg, "memory_cluster", {})
    if args.output_path:
        memory_cluster_cfg["keyframe_dir"] = os.path.abspath(
            os.path.expanduser(args.output_path)
        )
    local_map_snapshot = load_local_map_snapshot(replay_dir)
    local_map_manager = build_stub_local_map_manager(
        local_map_snapshot, metadata.get("class_lookup")
    )
    if local_map_snapshot is None:
        logger.warning(
            "[MemoryClusterDebug] No local_map snapshot; top-down view uses representative frames only."
        )

    manager = MemoryClusterManager(
        cfg=memory_cluster_cfg,
        anchor_whitelist=set(metadata.get("anchor_whitelist") or []),
        class_lookup=metadata.get("class_lookup"),
        clip_feature_fn=None,
    )

    frame_files = sorted(glob.glob(os.path.join(replay_dir, "frame_*.pkl.gz")))
    if not frame_files:
        logger.warning(
            "[MemoryClusterDebug] No recorded frames found in %s", replay_dir
        )
        return

    max_frames = args.max_frames
    if max_frames is not None:
        frame_files = frame_files[:max_frames]

    logger.info("[MemoryClusterDebug] Replaying %d frames", len(frame_files))
    for idx, frame_path in enumerate(frame_files, start=1):
        frame = load_frame(frame_path)
        observations = build_observations(frame.get("observations", []))
        clip_feature = frame.get("clip_feature")

        manager.process_frame(
            frame_idx=frame.get("frame_idx", idx - 1),
            color_image=frame.get("color"),
            pose=frame.get("pose"),
            observations=observations,
            precomputed_clip_feature=clip_feature,
        )

    manager.log_anchor_instances_summary(local_map_manager=local_map_manager)
    logger.info("[MemoryClusterDebug] Replay complete. Keyframes saved to %s", manager.keyframe_dir)


if __name__ == "__main__":
    main()

